"""Train, evaluate, version and serve the target classifier.

Training protocol:
  * split by recording session into train / validation / test (70/15/15 per
    class) so near-duplicate frames never straddle the split;
  * fit several candidate algorithms, pick the best on validation;
  * report the held-out test metrics of the chosen model only;
  * tune the alert probability threshold on validation (FPR <= 10% target);
  * k-fold cross-validation (grouped by session) for a variance estimate;
  * also fit a shallow decision tree that is exported as MicroPython so the
    classifier can run on the Pico itself.
"""
import json
import random
import time

import joblib
import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (accuracy_score, confusion_matrix, f1_score, precision_recall_fscore_support,
                             roc_auc_score, roc_curve)
from sklearn.model_selection import GroupKFold, StratifiedKFold, cross_val_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.tree import DecisionTreeClassifier

from .config import LABELS, MODELS_DIR, TARGET_LABEL
from .features import FEATURE_NAMES

ACTIVE_FILE = MODELS_DIR / "active.json"
REQUIRED_MODEL_ACCURACY = 0.80


def candidates():
    return {
        "random_forest": RandomForestClassifier(n_estimators=120, max_depth=14, min_samples_leaf=2,
                                                class_weight="balanced", n_jobs=-1, random_state=0),
        "gradient_boosting": HistGradientBoostingClassifier(max_iter=200, learning_rate=0.08, random_state=0),
        "logistic_regression": make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000, C=1.0,
                                                                                 class_weight="balanced")),
        "decision_tree_pico": DecisionTreeClassifier(max_depth=5, min_samples_leaf=5, class_weight="balanced",
                                                     random_state=0),
    }


def split_by_session(y, groups, sessions, seed=0):
    """Assign whole sessions to train/val/test per class. Returns masks + mode."""
    rng = random.Random(seed)
    by_label = {}
    for s in sessions:
        by_label.setdefault(s["label"], []).append(s["id"])
    if all(len(v) >= 4 for v in by_label.values()) and len(by_label) >= 2:
        role = {}
        for ids in by_label.values():
            ids = ids[:]
            rng.shuffle(ids)
            n = len(ids)
            n_test = max(1, round(0.15 * n)); n_val = max(1, round(0.15 * n))
            for i, sid in enumerate(ids):
                role[sid] = "test" if i < n_test else "val" if i < n_test + n_val else "train"
        r = np.array([role.get(g, "train") for g in groups])
        return r == "train", r == "val", r == "test", "grouped_by_session"
    # Fallback: random frame-level stratified split (optimistic: correlated frames)
    idx = np.arange(len(y))
    rs = np.random.RandomState(seed)
    tr, va, te = np.zeros(len(y), bool), np.zeros(len(y), bool), np.zeros(len(y), bool)
    for lab in np.unique(y):
        li = idx[y == lab].copy(); rs.shuffle(li)
        n = len(li); nt = max(1, int(0.15 * n)); nv = max(1, int(0.15 * n))
        te[li[:nt]] = True; va[li[nt:nt + nv]] = True; tr[li[nt + nv:]] = True
    return tr, va, te, "random_frames (record >=4 sessions per class for an honest split)"


def tune_threshold(p_target, y_bin, max_fpr=0.10):
    best_t, best = 0.5, -1
    # 0.2-0.8 only: extreme thresholds tuned on a few validation sessions don't generalize
    for t in np.linspace(0.2, 0.8, 61):
        pred = p_target >= t
        tp = np.sum(pred & y_bin); fp = np.sum(pred & ~y_bin)
        fn = np.sum(~pred & y_bin); tn = np.sum(~pred & ~y_bin)
        fpr = fp / max(1, fp + tn); tpr = tp / max(1, tp + fn)
        # balanced accuracy, FPR cap, and on ties prefer thresholds near 0.5
        score = (tpr + 1 - fpr) / 2 - (1.0 if fpr > max_fpr else 0) - 1e-3 * abs(t - 0.5)
        if score > best:
            best, best_t = score, float(t)
    return round(best_t, 2)


def binary_metrics(p_target, y_bin, threshold):
    pred = p_target >= threshold
    tp = int(np.sum(pred & y_bin)); fp = int(np.sum(pred & ~y_bin))
    fn = int(np.sum(~pred & y_bin)); tn = int(np.sum(~pred & ~y_bin))
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn,
            "accuracy": (tp + tn) / max(1, tp + tn + fp + fn),
            "fpr": fp / max(1, fp + tn), "fnr": fn / max(1, fn + tp),
            "precision": tp / max(1, tp + fp), "recall": tp / max(1, tp + fn)}


def export_tree_micropython(tree: DecisionTreeClassifier, classes) -> str:
    t = tree.tree_
    lines = ["# Auto-generated by ExamGuard server: shallow decision tree for the Pico.",
             "# Feature order: " + ", ".join(FEATURE_NAMES),
             "CLASSES = %r" % list(classes), "", "def predict(f):"]

    def rec(node, depth):
        ind = "    " * depth
        if t.children_left[node] == -1:
            counts = t.value[node][0]
            lines.append(f"{ind}return {int(np.argmax(counts))}  # {classes[int(np.argmax(counts))]}")
            return
        lines.append(f"{ind}if f[{t.feature[node]}] <= {t.threshold[node]:.4f}:  # {FEATURE_NAMES[t.feature[node]]}")
        rec(t.children_left[node], depth + 1)
        lines.append(f"{ind}else:")
        rec(t.children_right[node], depth + 1)

    rec(0, 1)
    return "\n".join(lines) + "\n"


def train(X, y, groups, sessions, algorithms=None, progress=lambda m: None):
    if len(X) < 30 or len(np.unique(y)) < 2:
        raise ValueError("Need at least 30 frames from 2+ classes. Record or generate data first.")
    t_start = time.time()
    tr, va, te, split_mode = split_by_session(y, groups, sessions)
    classes = [c for c in LABELS if c in set(y)]
    t_idx = classes.index(TARGET_LABEL) if TARGET_LABEL in classes else None

    board = []
    fitted = {}
    for name, clf in candidates().items():
        if algorithms and name not in algorithms:
            continue
        progress(f"Training {name}...")
        t0 = time.time()
        clf.fit(X[tr], y[tr])
        fit_s = time.time() - t0
        va_acc = accuracy_score(y[va], clf.predict(X[va]))
        te_acc = accuracy_score(y[te], clf.predict(X[te]))
        fitted[name] = clf
        board.append({"algorithm": name, "val_accuracy": round(va_acc, 4), "test_accuracy": round(te_acc, 4),
                      "fit_seconds": round(fit_s, 2)})
    board.sort(key=lambda r: -r["val_accuracy"])
    best_name = board[0]["algorithm"]
    model = fitted[best_name]
    progress(f"Best on validation: {best_name}. Evaluating on held-out test set...")

    proba_cls = list(model.classes_)
    order = [proba_cls.index(c) for c in classes]
    p_te = model.predict_proba(X[te])[:, order]
    p_va = model.predict_proba(X[va])[:, order]
    pred_te = np.array(classes)[np.argmax(p_te, axis=1)]
    acc = accuracy_score(y[te], pred_te)
    prec, rec, f1, sup = precision_recall_fscore_support(y[te], pred_te, labels=classes, zero_division=0)
    cm = confusion_matrix(y[te], pred_te, labels=classes)

    target = {}
    if t_idx is not None:
        yb_va = y[va] == TARGET_LABEL; yb_te = y[te] == TARGET_LABEL
        thr = tune_threshold(p_va[:, t_idx], yb_va)
        target = {"threshold": thr, **binary_metrics(p_te[:, t_idx], yb_te, thr)}
        if yb_te.any() and (~yb_te).any():
            fpr, tpr, _ = roc_curve(yb_te, p_te[:, t_idx])
            step = max(1, len(fpr) // 60)
            target["roc"] = [[round(a, 4), round(b, 4)] for a, b in zip(fpr[::step], tpr[::step])] + [[1.0, 1.0]]
            target["auc"] = round(roc_auc_score(yb_te, p_te[:, t_idx]), 4)

    progress("Cross-validating...")
    trva = tr | va
    n_groups = len(set(groups[trva]))
    try:
        if split_mode == "grouped_by_session" and n_groups >= 5:
            cv = cross_val_score(candidates()[best_name], X[trva], y[trva], groups=groups[trva],
                                 cv=GroupKFold(n_splits=5))
        else:
            cv = cross_val_score(candidates()[best_name], X[trva], y[trva], cv=StratifiedKFold(5, shuffle=True,
                                                                                            random_state=0))
        cv_res = {"mean": round(float(cv.mean()), 4), "std": round(float(cv.std()), 4), "folds": [round(float(v), 4) for v in cv]}
    except ValueError as e:
        cv_res = {"error": str(e)}

    progress("Permutation feature importance...")
    pi = permutation_importance(model, X[te], y[te], n_repeats=5, random_state=0, n_jobs=1)
    importance = sorted([{"feature": n, "importance": round(float(m), 4), "std": round(float(s), 4)}
                         for n, m, s in zip(FEATURE_NAMES, pi.importances_mean, pi.importances_std)],
                        key=lambda r: -r["importance"])

    progress("Learning curve...")
    curve = []
    rs = np.random.RandomState(0)
    tr_idx = np.where(tr)[0]
    for frac in (0.1, 0.25, 0.5, 0.75, 1.0):
        sub = rs.choice(tr_idx, max(10, int(frac * len(tr_idx))), replace=False)
        if len(np.unique(y[sub])) < 2:
            continue
        m = candidates()[best_name].fit(X[sub], y[sub])
        curve.append({"fraction": frac, "train_frames": int(len(sub)),
                      "test_accuracy": round(accuracy_score(y[te], m.predict(X[te])), 4)})

    # Per-condition accuracy on the test set (distance / orientation / environment)
    meta = {s["id"]: s for s in sessions}
    cond = {"target_distance_cm": {}, "orientation": {}, "environment": {}}
    for g, yt, yp in zip(groups[te], y[te], pred_te):
        s = meta.get(g, {})
        for key in cond:
            k = str(int(s.get(key, 0))) if key == "target_distance_cm" else str(s.get(key, "?"))
            c = cond[key].setdefault(k, [0, 0]); c[0] += int(yt == yp); c[1] += 1
    cond = {k: {kk: {"accuracy": round(a / n, 4), "n": n} for kk, (a, n) in v.items()} for k, v in cond.items()}

    # Inference cost on this machine
    if hasattr(model, "n_jobs"):
        model.n_jobs = 1
    one = X[te][:1]
    t0 = time.perf_counter()
    for _ in range(100):
        model.predict_proba(one)
    infer_ms = (time.perf_counter() - t0) * 10

    # Pico-exportable tree trained on train+val
    tree = DecisionTreeClassifier(max_depth=4, min_samples_leaf=5, class_weight="balanced", random_state=0)
    tree.fit(X[trva], y[trva])
    pico_code = export_tree_micropython(tree, list(tree.classes_))
    pico_acc = accuracy_score(y[te], tree.predict(X[te]))

    version = time.strftime("v%Y%m%d-%H%M%S")
    vdir = MODELS_DIR / version
    vdir.mkdir(parents=True, exist_ok=True)
    joblib.dump({"model": model, "classes": classes, "features": FEATURE_NAMES}, vdir / "model.joblib")
    (vdir / "pico_model.py").write_text(pico_code)
    synthetic_share = sum(s["frames"] for s in sessions if s.get("synthetic")) / max(1, sum(s["frames"] for s in sessions))
    meta_out = {
        "version": version, "created": time.time(), "algorithm": best_name, "classes": classes,
        "features": FEATURE_NAMES, "split_mode": split_mode,
        "n_frames": {"train": int(tr.sum()), "val": int(va.sum()), "test": int(te.sum())},
        "n_sessions": len(sessions), "synthetic_share": round(synthetic_share, 3),
        "test_accuracy": round(acc, 4), "macro_f1": round(f1_score(y[te], pred_te, average="macro"), 4),
        "meets_requirement": bool(acc >= REQUIRED_MODEL_ACCURACY),
        "per_class": [{"label": c, "precision": round(float(p), 4), "recall": round(float(r), 4),
                       "f1": round(float(f), 4), "support": int(s)} for c, p, r, f, s in zip(classes, prec, rec, f1, sup)],
        "confusion_matrix": cm.tolist(), "target": target, "cross_validation": cv_res,
        "leaderboard": board, "feature_importance": importance, "learning_curve": curve,
        "per_condition": cond, "inference_ms": round(infer_ms, 3),
        "model_kb": round((vdir / "model.joblib").stat().st_size / 1024, 1),
        "pico_tree": {"depth": 4, "test_accuracy": round(float(pico_acc), 4), "lines": pico_code.count("\n")},
        "train_seconds": round(time.time() - t_start, 1),
    }
    (vdir / "meta.json").write_text(json.dumps(meta_out, indent=1))
    progress("Done.")
    return meta_out


class ModelStore:
    def __init__(self):
        self.model = None
        self.meta = None
        self.threshold = 0.5
        active = json.loads(ACTIVE_FILE.read_text()).get("version") if ACTIVE_FILE.exists() else None
        if active:
            try:
                self.activate(active)
            except FileNotFoundError:
                pass

    def list(self):
        out = []
        for p in sorted(MODELS_DIR.glob("v*/meta.json"), reverse=True):
            m = json.loads(p.read_text())
            out.append({k: m.get(k) for k in ("version", "created", "algorithm", "test_accuracy", "macro_f1",
                                              "meets_requirement", "synthetic_share", "split_mode", "n_sessions")}
                       | {"active": self.meta is not None and self.meta["version"] == m["version"],
                          "fpr": m.get("target", {}).get("fpr")})
        return out

    def get_meta(self, version):
        return json.loads((MODELS_DIR / version / "meta.json").read_text())

    def activate(self, version):
        bundle = joblib.load(MODELS_DIR / version / "model.joblib")
        est = bundle["model"]
        if hasattr(est, "n_jobs"):
            est.n_jobs = 1  # single-sample live inference: threads only add latency
        self.model = bundle
        self.meta = self.get_meta(version)
        self.threshold = self.meta.get("target", {}).get("threshold", 0.5)
        ACTIVE_FILE.write_text(json.dumps({"version": version}))

    def deactivate(self):
        self.model, self.meta = None, None
        ACTIVE_FILE.unlink(missing_ok=True)

    def predict(self, vec):
        if not self.model:
            return None
        m = self.model["model"]
        p = m.predict_proba(vec.reshape(1, -1))[0]
        probs = {c: float(p[list(m.classes_).index(c)]) for c in self.model["classes"]}
        return {"probs": probs, "label": max(probs, key=probs.get), "p_target": probs.get(TARGET_LABEL, 0.0)}
